// Generates docs/DATA_REVIEW.md: every medium- or low-confidence data item.
import { writeFileSync } from 'node:fs';
import { DATA_REGISTRY } from '../../src/data/registry';

interface Item { file: string; path: string; value: string; confidence: string; note: string }

const items: Item[] = [];
const fmt = (v: unknown): string => {
  if (typeof v === 'number') return Number.isInteger(v) ? v.toLocaleString('en-US') : String(Math.round(v * 10000) / 10000);
  if (Array.isArray(v)) return `[${v.map(fmt).join(', ')}]`;
  if (typeof v === 'string') return v;
  return JSON.stringify(v);
};

function isAnnualArray(v: unknown): v is { year: number; value: number; confidence: string; source?: string }[] {
  return Array.isArray(v) && v.length > 0 && v.every((p) => p && typeof p === 'object' && 'year' in p && 'value' in p && 'confidence' in p);
}

function walk(file: string, path: string, v: unknown, seen: Set<unknown>): void {
  if (!v || typeof v !== 'object' || seen.has(v)) return;
  seen.add(v);
  if (isAnnualArray(v)) {
    // Group consecutive years with the same confidence.
    let run: typeof v = [];
    const flush = () => {
      if (!run.length) return;
      const c = run[0].confidence;
      if (c !== 'high') {
        const yrs = run.length === 1 ? `${run[0].year}` : `${run[0].year}–${run[run.length - 1].year}`;
        items.push({ file, path: `${path} (${yrs})`, value: run.map((p) => fmt(p.value)).join(', '), confidence: c, note: run[0].source ?? '' });
      }
      run = [];
    };
    for (const p of v) {
      if (run.length && (p.confidence !== run[0].confidence || p.source !== run[0].source)) flush();
      run.push(p);
    }
    flush();
    return;
  }
  const o = v as Record<string, unknown>;
  if ('confidence' in o && (o.confidence === 'medium' || o.confidence === 'low')) {
    const label = 'value' in o ? fmt(o.value) : 'headline' in o ? `${(o as { date?: number[] }).date?.join('-')}: ${o.headline}` : 'name' in o ? `${o.name} (${o.availableFrom ?? ''}–${o.availableTo ?? ''})` : 'fromYear' in o ? `from ${o.fromYear}` : '';
    items.push({ file, path, value: label, confidence: String(o.confidence), note: String(o.note ?? o.source ?? o.notes ?? o.confidenceNote ?? '') });
  }
  for (const k of Object.keys(o)) {
    if (k === 'confidence') continue;
    const child = o[k];
    const c = child as { id?: unknown; brandId?: unknown; components?: unknown } | null;
    // Maker lines (D-129) are keyed by brand and what they make.
    const id = c && typeof c === 'object' && 'id' in c ? String(c.id) : c && typeof c === 'object' && 'brandId' in c ? `${String(c.brandId)}:${Array.isArray(c.components) ? c.components.join('+') : ''}` : k;
    walk(file, Array.isArray(o) ? `${path}[${id}]` : path ? `${path}.${k}` : k, child, seen);
  }
}

for (const [file, mod] of Object.entries(DATA_REGISTRY)) {
  const seen = new Set<unknown>();
  for (const [name, val] of Object.entries(mod)) walk(file, name, val, seen);
}

const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const byFile = new Map<string, Item[]>();
for (const it of items) byFile.set(it.file, [...(byFile.get(it.file) ?? []), it]);
let md = `# Data review\n\nGenerated by \`npm run data:review\`. Lists every **medium** or **low** confidence data item so it can be checked against industry experience. Correct values in the named file; the engine reads them directly.\n\n`;
md += `Totals: ${items.filter((i) => i.confidence === 'low').length} low, ${items.filter((i) => i.confidence === 'medium').length} medium.\n\n`;
md += `Cost anchors are 2024 dollars scaled by the construction-cost index; other dollar constants are 2024 dollars scaled by CPI.\n\n`;
for (const [file, list] of byFile) {
  md += `## src/data/${file}\n\n| Item | Value | Confidence | Note / source |\n|---|---|---|---|\n`;
  for (const it of list) md += `| ${esc(it.path)} | ${esc(it.value).slice(0, 400)} | ${it.confidence} | ${esc(it.note)} |\n`;
  md += '\n';
}
writeFileSync('docs/DATA_REVIEW.md', md);
console.log(`Wrote docs/DATA_REVIEW.md with ${items.length} items.`);
